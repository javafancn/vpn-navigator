#!/usr/bin/env python3
"""Validate bilingual coverage, placeholders, exemptions and embedded catalog."""
import argparse
import json
import re
from pathlib import Path
from swift_string_literals import strings, CJK

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'Resources/Localization/catalog.json'
GENERATED = ROOT / 'Sources/VPNNavigatorCore/EmbeddedLocalizationCatalog.swift'

def generated(rows):
    text = json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
    return '// Generated by scripts/check-localization.py --generate; edit the JSON catalog.\n' + 'enum EmbeddedLocalizationCatalog {\n    static let json = #"""\n' + text + '\n"""#\n}\n'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', action='store_true')
    args = parser.parse_args()
    rows = json.loads(CATALOG.read_text())
    keys = {r['key'] for r in rows}
    assert len(rows) == len(keys), 'Duplicate localization keys'
    for row in rows:
        assert row['zh'] and row['en'], row
        assert not CJK.search(row['en']), ('English contains untranslated text', row)
        tokens = lambda value: sorted(re.findall(r'\{\d+\}', value))
        assert tokens(row['key']) == tokens(row['zh']) == tokens(row['en']), row
    expected = generated(rows)
    if args.generate:
        GENERATED.write_text(expected)
    assert GENERATED.read_text() == expected, 'Run scripts/check-localization.py --generate'
    exemptions = {(e['path'], e['key']) for e in json.loads((CATALOG.parent / 'exemptions.json').read_text())}
    exemptions.add(('Sources/VPNNavigatorCore/Localization.swift', '简体中文'))
    def recursive_strings(source):
        for item in strings(source):
            yield source, item
            for kind, value in item['parts']:
                if kind == 'expression':
                    yield from recursive_strings(value)
    missing = []
    for folder in ['Sources/VPNNavigatorApp', 'Sources/VPNNavigatorCore']:
        for path in (ROOT / folder).glob('*.swift'):
            if 'SelfTest' in path.name or path == GENERATED:
                continue
            source = path.read_text()
            for context, item in recursive_strings(source):
                if not any(CJK.search(t) for kind, t in item['parts'] if kind == 'literal'):
                    continue
                before = context[max(0, item['start'] - 35):item['start']]
                if re.search(r'L10n\.(text|format)\(\s*$', before):
                    key = json.loads(item['source'])
                    assert key in keys, ('Missing catalog entry', str(path), key)
                else:
                    key = ''.join(t for kind, t in item['parts'] if kind == 'literal')
                    if (str(path.relative_to(ROOT)), key) not in exemptions:
                        missing.append((str(path.relative_to(ROOT)), key))
    assert not missing, ('Unlocalized production literals', missing)
    print(f'PASS localization: {len(rows)} bilingual entries, matching placeholders, explicit metadata/raw-value exemptions and synchronized embedded catalog')

if __name__ == '__main__':
    main()
